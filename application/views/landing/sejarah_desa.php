        <h2 class="mb-3 mt-4">Selayang Pandang Desa Blahbatuh</h2>

        <p>
        Desa Blahbatuh merupakan salah satu desa yang berada di wilayah Kecamatan Blahbatuh. Desa ini memiliki luas wilayah sebesar 4,67 km² dan terletak pada ketinggian sekitar 150 meter di atas permukaan laut. Jumlah penduduk Desa Blahbatuh tercatat sebanyak 10.073 jiwa yang tersebar di 12 banjar dinas, yaitu Banjar Dinas Laud, Pande, Tusan, Kebon, Tengah, Tubuh, Babakan, Antugan, Darmatiaga, Satria, Pokas, dan Teruna. Di wilayah Desa Blahbatuh juga terdapat lima desa adat, yaitu Desa Adat Blahbatuh, Teruna, Antugan, Satria, dan Darmatiaga.
        </p>

        <p>
        Adapun batas-batas wilayah Desa Blahbatuh adalah sebagai berikut: sebelah utara berbatasan dengan Desa Buruan, sebelah timur berbatasan dengan Desa Belega, sebelah selatan berbatasan dengan Desa Saba, dan sebelah barat berbatasan dengan Kecamatan Sukawati.
        </p>

        <p>
        Berdasarkan peninggalan arkeologi yang terdapat di beberapa Pura Kahyangan Tiga, antara lain Pura Puseh Desa Adat Blahbatuh, Pura Dalem Maya Desa Adat Teruna, Pura Puseh Desa Adat Antugan, Pura Tengaling Desa Adat Satria, serta Pura Gaduh Desa Adat Blahbatuh, dapat diketahui bahwa Desa Blahbatuh merupakan salah satu desa tua di Bali dan telah ada sejak zaman Bali Kuno.
        </p>

        <p>
        Salah satu peninggalan arkeologi yang berkaitan langsung dengan kelahiran Desa Blahbatuh adalah Patung Hulu yang terletak di Pura Puseh Desa Adat Blahbatuh. Patung Hulu tersebut dipresentasikan sebagai simbol penyatuan berbagai sekte kepercayaan yang berpengaruh di Bali pada masa itu.
        </p>

        <p>
        Wujud Patung Hulu digambarkan dengan mata yang besar dan mulut lebar bertaring yang melambangkan Sekte Bhaerawa. Telinga lebar melambangkan Sekte Isyana atau Iswara, rambut berkerucut melambangkan Sekte Siwa, dan rambut keriting bulat-bulat melambangkan Sekte Sogata atau Buddhis. Selain itu, pola struktur pura juga menggunakan konsep Tri Angga, yaitu seluruh pelinggih ditempatkan dalam satu area utama.
        </p>

        <p>
        Keberadaan Patung Hulu tersebut, jika dihubungkan dengan artefak pemedal atau lawang Pura Puseh yang diapit oleh dua patung gajah, menunjukkan angka tahun Candra Sangkala yang lazim digunakan dalam penulisan prasasti sebagai penanda tahun pembuatannya. Hal tersebut menjadi dasar awal dalam penelusuran tahun kelahiran Desa Blahbatuh.
        </p>

        <p>
        Tahun Candra Sangkala yang dimaksud terdiri atas simbol gajah dan lawang. Gajah memiliki nilai angka 8, sedangkan lawang atau pemedal bernilai angka 9. Dengan demikian, nilai tahun dari Candra Sangkala tersebut adalah 898 Saka atau bertepatan dengan tahun 976 Masehi.
        </p>

        <p>
        Pada masa itu, Bali diperintah oleh raja yang bernama Sang Ratu Sri Jana Sadhu Warmadewa yang berkuasa pada tahun 897 Saka atau 975 Masehi. Beliau merupakan kakek dari Prabu Sri Dharmodayana yang lebih dikenal dengan Raja Udayana, yang memerintah di Bali pada tahun 923 Saka atau 1001 Masehi.
        </p>

        <p>
        Berdasarkan fakta historis tersebut, dapat disimpulkan dan dipastikan bahwa Desa Blahbatuh telah ada sejak tahun 976 Masehi. Penetapan kelahiran Desa Blahbatuh didasarkan pada perhitungan tahun Candra Sangkala yang ditemukan pada pemedal Pura Puseh dengan menggunakan sistem perhitungan tahun nonkabisat atau tahun khusus. Oleh karena itu, ditetapkan bahwa hari kelahiran Desa Blahbatuh jatuh pada tanggal 7 September 976 dan diperingati sebagai hari jadi Desa Blahbatuh.
        </p>

        <p>
        Nama Blahbatuh sebagai nama desa di Kecamatan Blahbatuh, Kabupaten Gianyar, Bali, didasarkan pada Prasasti Sading, Purana Pura Gaduh, dan Babad Karang Buncing. Dalam sumber-sumber tersebut disebutkan bahwa Ki Jaya Katong diperintahkan oleh kakeknya, Sri Maharaja Jaya Sakti, sekitar tahun 1133–1150 Masehi untuk membangun Desa Blahbatuh secara spiritual serta mendirikan gapura yang artistik dan megah sebagai pintu gerbang Pura Puseh Desa Adat Blahbatuh. Gapura tersebut melambangkan puncak Gunung Mahameru.
        </p>

        <p>
        Dalam beberapa sumber sejarah, Desa Blahbatuh juga disebut dengan nama Wadwasila, yang bermakna bahwa Blahbatuh pada masa lampau merupakan tempat permukiman bala tentara atau pasukan yang memiliki kesaktian serta aji kanuragan. Hal ini dapat dibuktikan dengan adanya tarian wali atau sakral Baris Bala Batu yang dipentaskan setiap pelaksanaan pujawali di Pura Dalem Maya, yang selesai dibangun pada tahun 1197 Saka atau 1275 Masehi.
        </p>

        <p>
        Baris Bala Batu menjadi ikon Wadwasila, di mana ikon tersebut dijadikan salah satu sumber rujukan dalam penamaan tempat atau wilayah. Secara etimologis, istilah bala batu berasal dari kata bala yang berarti pasukan dan batu yang berarti kekuatan.
        </p>

        <p>
        Kajian arkeologi di Bali banyak dilakukan oleh para pakar Belanda. Dalam pelafalan istilah bala batu, bunyi pengucapannya terdengar seolah-olah memiliki konsonan “h” di akhir kata, sehingga terdengar seperti “balah batuh”. Dalam kajian kebahasaan, khususnya fonologi, masyarakat Bali cenderung mengucapkan kata secara singkat dan cepat. Oleh karena itu, pelafalan “balah batuh” lama-kelamaan berubah menjadi “Blahbatuh”. Hal inilah yang menjadi dasar penamaan Desa Blahbatuh hingga saat ini.
        </p>

        <p>
        Desa Blahbatuh juga dikenal sebagai basis desa pejuang kemerdekaan Republik Indonesia dalam melawan NICA dan dikenal dengan julukan Pasukan Baju Karung. Hal ini dibuktikan dengan didirikannya Monumen Pahlawan Kemerdekaan Republik Indonesia di perempatan Desa Blahbatuh serta pembangunan tugu pahlawan untuk mengenang pejuang I Wayan Darya yang gugur ditembak oleh pasukan NICA. Tercatat sebanyak 78 orang warga Blahbatuh sebagai pejuang kemerdekaan Republik Indonesia.
        </p>

        <p>
        Pada awalnya, Desa Blahbatuh dipimpin oleh seorang tokoh bernama Ki Jaya Katong, putra dari Sang Sidhi Mantra Dewa dan cucu dari Maharaja Jaya Sakti yang berkuasa di Bali pada tahun 1133–1150 Masehi. Setelah Ki Jaya Katong wafat, kepemimpinan Desa Blahbatuh dilanjutkan oleh putranya yang bernama Ki Karang Buncing. Salah satu keturunannya yang menjadi tokoh legendaris bagi masyarakat Bali adalah Ki Kebo Iwa atau Kebo Taruna, yang dikenal karena ketangkasan, kekebalan, dan keterampilannya di medan laga. Beliau kemudian diangkat menjadi patih di Kerajaan Bali pada masa pemerintahan Raja Sri Antasura Ratna Bumi Banten di Bedahulu.
        </p>

        <p>
        Eksistensi Ki Kebo Iwa sangat penting dalam menjaga kejayaan Bali pada periode tahun 1337–1343 Masehi. Beliau wafat setelah diperdaya melalui tipu muslihat Gajah Mada dengan tujuan menundukkan kekuasaan Raja Bedahulu. Setelah wafatnya Ki Kebo Iwa, kepemimpinan di Blahbatuh dilanjutkan oleh saudaranya, Ki Bendesa Gede Karang Buncing, yang secara turun-temurun kepemimpinannya dilanjutkan oleh keluarga Ki Karang Buncing.
        </p>

        <p>
        Selanjutnya, Jro Wayan Gede Karang Buncing meminta salah satu putra Dewa Agung Pemayun dari Tampaksiring, yaitu Cokorda Made Pemayun, untuk dijadikan junjungan di Bumi Blahbatuh guna bersinergi dalam memimpin Desa Blahbatuh. Pada kesempatan lain, berdasarkan kesepakatan antara Raja Gianyar I Dewa Manggis Sakti dengan I Gusti Gede Kerug serta Jro Wayan Gede Karang Buncing, Gusti Gede Kerug berpindah dari Puri Tojan ke Blahbatuh dan selanjutnya memimpin Desa Blahbatuh dengan gelar Gusti Ngurah Jelantik.
        </p>

        <p>
        Pada masa setelah kemerdekaan Republik Indonesia, peralihan kepemimpinan pemerintahan Desa Blahbatuh, mulai dari masa Orde Baru hingga masa Reformasi, dilaksanakan secara demokratis berdasarkan peraturan perundang-undangan yang berlaku, dengan sebutan perbekel atau kepala desa.
        </p>

        
